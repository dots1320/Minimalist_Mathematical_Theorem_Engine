# Job planning
# --------------------------------------------------------------------------- #

def plan_jobs(target: int, rng: random.Random) -> list[dict]:
    """
    Build the full job queue. Each job is a dict describing what kind of
    sample to generate. Mix is calibrated to the target size.
    """
    fractions = {
        "wiki": 0.50,
        "base_theorem": 0.10,
        "fallacy": 0.10,
        "already_correct": 0.20,
        "non_math": 0.05,
        "ambiguous": 0.05,
    }
    counts = {k: int(target * v) for k, v in fractions.items()}
    # Round any leftover to wiki
    counts["wiki"] += target - sum(counts.values())

    jobs = []

    # Load wiki theorems
    wiki_path = "data/wikipedia_theorems.json"
    wiki = []
    if os.path.exists(wiki_path):
        with open(wiki_path, "r", encoding="utf-8") as f:
            for w in json.load(f):
                if is_usable_wiki_theorem(w.get("statement", "")):
                    wiki.append(w)
    print(f"[INFO] Filtered wiki theorems: {len(wiki)} usable / target {counts['wiki']} jobs")

    if wiki:
        for _ in range(counts["wiki"]):
            w = rng.choice(wiki)
            jobs.append({
                "kind": "correction",
                "name": w["name"][:80],
                "stmt": w["statement"],
                "mode": rng.choice(["auto", "auto", "drop", "informal", "garble", "lower"]),
            })

    for _ in range(counts["base_theorem"]):
        name, stmt = rng.choice(BASE_THEOREMS)
        jobs.append({
            "kind": "correction",
            "name": name,
            "stmt": stmt,
            "mode": rng.choice(["auto", "auto", "drop", "informal", "garble"]),
        })

    for _ in range(counts["fallacy"]):
        wrong, correct, hint = rng.choice(COMMON_FALLACIES)
        jobs.append({
            "kind": "fallacy",
            "wrong": wrong,
            "correct": correct,
            "hint": hint,
        })

    if wiki:
        for _ in range(counts["already_correct"]):
            w = rng.choice(wiki)
            jobs.append({
                "kind": "already_correct",
                "name": w["name"][:80],
                "stmt": w["statement"],
            })
    else:
        for _ in range(counts["already_correct"]):
            name, stmt = rng.choice(BASE_THEOREMS)
            jobs.append({"kind": "already_correct", "name": name, "stmt": stmt})

    for _ in range(counts["non_math"]):
        jobs.append({"kind": "non_math", "query": rng.choice(NON_MATH_QUERIES)})

    # Ambiguous: take a base theorem, truncate it to make it ambiguous
    for _ in range(counts["ambiguous"]):
        name, stmt = rng.choice(BASE_THEOREMS)
        words = stmt.split()
        keep = max(3, int(len(words) * rng.uniform(0.3, 0.6)))
        truncated = " ".join(words[:keep])
        jobs.append({
            "kind": "correction",
            "name": name,
            "stmt": stmt,
            "mode": "preserve",
            "override_bad": truncated,
        })

    rng.shuffle(jobs)
    print(f"[INFO] Planned {len(jobs)} jobs: " +
          " ".join(f"{k}={v}" for k, v in counts.items()))
    return jobs


# --------------------------------------------------------------------------- #
# Main loop
# --------------------------------------------------------------------------- #

def run_job(job: dict, rng: random.Random, generate_fn,
            max_retries: int = 3,
            use_reference_answer: bool = False) -> dict | None:
    """Returns a built record or None if all attempts fail."""
    expected_answer = None
    if job["kind"] in ("correction",):
        prefix, body, suffix = wrap_with_conversation("", rng)
        if "override_bad" in job:
            bad = job["override_bad"]
        else:
            bad = make_bad_note(job["stmt"], rng, mode=job.get("mode", "auto"))
        bad_full = f"{prefix}{bad}{suffix}".strip()
        good_full = f"{prefix}{job['stmt']}{suffix}".strip()
        expected_answer = good_full
        prompt = TEACHER_TASK_PROMPT.format(
            theorem_name=job["name"],
            reference=job["stmt"],
            bad_note=bad,
            prefix=prefix,
            suffix=suffix,
        )
        require_kw = True
    elif job["kind"] == "fallacy":
        prefix, body, suffix = wrap_with_conversation("", rng)
        bad = job["wrong"]
        if rng.random() < 0.2:
            bad = garble(bad, rng)
        bad_full = f"{prefix}{bad}{suffix}".strip()
        expected_answer = f"{prefix}{job['correct']}{suffix}".strip()
        prompt = TEACHER_TASK_PROMPT.format(
            theorem_name="Common Fallacy",
            reference=f"{job['correct']} (Hint: {job['hint']})",
            bad_note=bad,
            prefix=prefix,
            suffix=suffix,
        )
        require_kw = True
    elif job["kind"] == "already_correct":
        prefix, body, suffix = wrap_with_conversation("", rng)
        good_full = f"{prefix}{job['stmt']}{suffix}".strip()
        bad_full = good_full
        expected_answer = good_full
        prompt = TEACHER_ALREADY_CORRECT_PROMPT.format(
            theorem_name=job["name"],
            good_note=job["stmt"],
            prefix=prefix,
            suffix=suffix,
        )
        require_kw = False  # already-correct samples may have shorter think
    elif job["kind"] == "non_math":
        bad_full = job["query"]
        expected_answer = "(No mathematical theorem detected.)"
        prompt = TEACHER_NONMATH_PROMPT.format(query=job["query"])
        require_kw = False
    else:
        return None

    last_reason = "no_attempt"
    last_tokens = 0
    last_raw = ""
    for attempt in range(max_retries):
        # Attempt 0: fast greedy. Attempts 1+: sample with rising temp.
        do_sample = attempt > 0
        temp = 0.6 + 0.2 * attempt
        try:
            raw, n_tok = generate_fn(
                prompt,
                temperature=temp, do_sample=do_sample,
            )
            last_tokens = n_tok
            last_raw = raw
        except Exception as e:
            print(f"  [WARN] generation error (attempt {attempt + 1}): {e}")
            continue
        think, answer = extract_think_and_answer(raw)
        ok, reason = passes_quality(think, answer, require_keywords=require_kw)
        last_reason = reason
        if ok:
            if use_reference_answer and expected_answer:
                answer = expected_answer
            return (build_record(bad_full, think, answer), n_tok, attempt + 1, "ok", "")
    return (None, last_tokens, max_retries, last_reason, last_raw[:300])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--teacher-provider", choices=["local", "openai"], default="local",
                        help="Use local HF teacher or OpenAI API teacher.")
    parser.add_argument("--teacher", default="models/Qwen2.5-7B-Instruct",
                        help="Teacher model directory. Default: Qwen2.5-7B-Instruct (faster on 8GB GPU). "
                             "Use models/DeepSeek-R1-Distill-Qwen-7B for higher-quality CoT but ~10x slower.")
    parser.add_argument("--openai-model", default="mimo-v2.5-pro",
                        help="API model used when --teacher-provider=openai. "
                             "Default: mimo-v2.5-pro (xiaomi reasoning model with reasoning_content).")
    parser.add_argument("--openai-base-url", default=os.environ.get("OPENAI_BASE_URL", "https://token-plan-sgp.xiaomimimo.com/v1"),
                        help="OpenAI-compatible API base URL.")
    parser.add_argument("--api-workers", type=int, default=8,
                        help="Concurrent API workers for --teacher-provider=openai.")
    parser.add_argument("--api-timeout", type=int, default=120,
                        help="Per-request API timeout in seconds.")
    parser.add_argument("--api-http-retries", type=int, default=5,
                        help="HTTP retries for transient API errors.")
    parser.add_argument("--quality-retries", type=int, default=3,
                        help="Regenerate a sample this many times if quality filters fail.")
    parser.add_argument("--save-every", type=int, default=10,
                        help="Write partial file after this many accepted records.")
    parser.add_argument("--use-reference-answer", action="store_true",
                        help="Use the script's known corrected answer instead of the teacher answer.")
    parser.add_argument("--target", type=int, default=3000,
                        help="Number of samples to generate. Default 3000 (~3-5 hours on 8GB).")
    parser.add_argument("--output", default="data/student_notes_train_v2.json")
    parser.add_argument("--partial", default="data/student_notes_train_v2_partial.json")
    parser.add_argument("--stats", default="data/student_notes_train_v2_stats.txt")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--dry-run", action="store_true",
                        help="Generate --num samples then exit (smoke test)")
    parser.add_argument("--num", type=int, default=5,
                        help="Number of samples for --dry-run")
    parser.add_argument("--verbose", action="store_true",
                        help="Print full failure reason and partial generation when a sample fails")
    args = parser.parse_args()

    rng = random.Random(args.seed)
    use_reference_answer = args.use_reference_answer or args.teacher_provider == "openai"

    if args.teacher_provider == "local":
        if not os.path.exists(args.teacher):
            print(f"[FATAL] Teacher model not found: {args.teacher}")
            print("[HINT] Download with:")
            print("  huggingface-cli download deepseek-ai/DeepSeek-R1-Distill-Qwen-7B \\")
            print(f"    --local-dir {args.teacher}")
            print("  (or set HF_ENDPOINT=https://hf-mirror.com if HF is blocked)")
            sys.exit(1)

        model, tok = load_teacher(args.teacher)

        def generate_fn(prompt: str, **kwargs):
            return teacher_generate(model, tok, prompt, **kwargs)
    else:
        if not os.environ.get("OPENAI_API_KEY"):
            print("[FATAL] OPENAI_API_KEY is not set; cannot use --teacher-provider=openai")
            sys.exit(1)
        print(f"[INFO] Using OpenAI teacher model: {args.openai_model}")
        print(f"[INFO] API workers: {args.api_workers}")

        def generate_fn(prompt: str, **kwargs):
            return openai_generate(
                prompt,
                model=args.openai_model,
                base_url=args.openai_base_url,
                timeout=args.api_timeout,
                http_retries=args.api_http_retries,
                **kwargs,
            )

    if args.dry_run:
        print(f"\n[DRY RUN] Generating {args.num} samples")
        jobs = plan_jobs(args.num, rng)[:args.num]
        for i, job in enumerate(jobs):
            print(f"\n--- Job {i + 1}/{len(jobs)}: kind={job['kind']} ---")
            t0 = time.time()
            rec, n_tok, attempts, reason, partial = run_job(
                job, rng, generate_fn,
                max_retries=args.quality_retries,
                use_reference_answer=use_reference_answer,
            )
            dt = time.time() - t0
            tps = n_tok / dt if dt > 0 else 0
            if rec:
                print(f"  [OK] {dt:.1f}s  {n_tok} tok  {tps:.1f} tok/s  attempts={attempts}")
                print(f"  INPUT:  {rec['input'][:120]}")
                print(f"  OUTPUT: {rec['output'][:300]}")
            else:
                print(f"  [FAIL] {dt:.1f}s  {n_tok} tok  reason={reason}")
                print(f"  Partial generation (first 300 chars): {partial!r}")
        print("\n[DRY RUN DONE]")
        return

    # Resume support
    completed = []
    if os.path.exists(args.partial):
        try:
            with open(args.partial, "r", encoding="utf-8") as f:
                completed = json.load(f)
            print(f"[RESUME] Loaded {len(completed)} previously completed records")
        except Exception as e:
            print(f"[WARN] Could not parse {args.partial}: {e}. Starting fresh.")

    if len(completed) >= args.target:
        print(f"[INFO] Already have {len(completed)} >= target {args.target}. "
              f"Writing to {args.output} and exiting.")
        with open(args.output, "w", encoding="utf-8") as f:
            json.dump(completed[:args.target], f, ensure_ascii=False, indent=2)
        write_stats(completed[:args.target], args.stats)
        return

    remaining = args.target - len(completed)
    print(f"[INFO] Need {remaining} more samples (have {len(completed)} / target {args.target})")
    jobs = plan_jobs(remaining, rng)

    fail_counts = Counter()
    t_start = time.time()
    total_tokens = 0
    saved_since_partial = 0

    def save_partial():
        with open(args.partial, "w", encoding="utf-8") as f:
            json.dump(completed, f, ensure_ascii=False, indent=2)

    for i, job in enumerate(jobs, start=1):
        t0 = time.time()
        rec, n_tok, attempts, reason, partial = run_job(
            job, rng, generate_fn,
            max_retries=args.quality_retries,
            use_reference_answer=use_reference_answer,
        )
        dt = time.time() - t0
        total_tokens += n_tok
        tps = n_tok / dt if dt > 0 else 0
        status = "OK" if rec else "FAIL"
        retry_tag = f" retry={attempts}" if attempts > 1 else ""
        fail_tag = f" reason={reason}" if not rec else ""
        # Per-sample heartbeat — confirms the script is alive between batch reports
        print(f"  [{i}/{len(jobs)} {status}] {job['kind']:14s} {dt:5.1f}s "
              f"{n_tok:4d}tok {tps:5.1f}tok/s{retry_tag}{fail_tag}", flush=True)
        if not rec and args.verbose:
            print(f"    partial: {partial!r}")

        if rec:
            completed.append(rec)
            saved_since_partial += 1
        else:
            fail_counts[job["kind"]] += 1

        # Periodic summary + persistence
        if i % 25 == 0 or i == len(jobs):
            elapsed = time.time() - t_start
            rate = i / max(elapsed, 1e-3)
            eta = (len(jobs) - i) / max(rate, 1e-3)
            avg_tps = total_tokens / max(elapsed, 1e-3)
            print(f"=== [{i}/{len(jobs)}] kept={len(completed)} "
                  f"failed={sum(fail_counts.values())} "
                  f"rate={rate * 60:.1f}samples/min "
                  f"avg={avg_tps:.1f}tok/s "
                  f"eta={eta / 60:.0f}min ===", flush=True)
        if saved_since_partial >= max(args.save_every, 1):
            save_partial()
            saved_since_partial = 0

    if saved_since_partial:
        save_partial()

    # Final write
    print(f"\n[INFO] Done. Total kept: {len(completed)}")
    if fail_counts:
        print(f"[INFO] Failures by kind: {dict(fail_counts)}")
    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(completed, f, ensure_ascii=False, indent=2)
    print(f"[OK] Wrote {args.output}")
    write_stats(completed, args.stats)
    # Keep partial as backup until next run
    print(f"[INFO] Partial file kept at {args.partial} (delete manually if desired)")


def write_stats(records: list[dict], path: str):
    """Diagnostic report for the user to verify dataset quality."""
    n = len(records)
    if n == 0:
        return
    think_blocks = []
    answer_blocks = []
    for r in records:
        out = r["output"]
        m = THINK_RE.search(out)
        if m:
            think_blocks.append(m.group(1).strip())
            answer_blocks.append(out[m.end():].strip())
        else:
            answer_blocks.append(out.strip())

    unique_think = len({t[:80] for t in think_blocks})
    avg_think = sum(len(t) for t in think_blocks) / max(len(think_blocks), 1)
    avg_answer = sum(len(a) for a in answer_blocks) / max(len(answer_blocks), 1)

    boilerplate_hits = sum(
        1 for t in think_blocks
        if "rigorous form is" in t and "imprecise shorthand" in t
    )

    prefixes = Counter(r["input"][:25] for r in records)
    top_prefixes = prefixes.most_common(10)

    lines = [
        f"=== student_notes_train_v2 stats ===",
        f"total records: {n}",
        f"records with <think>: {len(think_blocks)} ({len(think_blocks) / n:.1%})",
        f"unique think openings (first 80 chars): {unique_think} "
        f"(diversity ratio: {unique_think / max(len(think_blocks), 1):.3f})",
        f"avg think length: {avg_think:.0f} chars",
        f"avg answer length: {avg_answer:.0f} chars",
        f"old-template hits: {boilerplate_hits} (target: 0)",
        f"",
        f"top 10 input prefixes (templates):",
    ]
    for p, c in top_prefixes:
        lines.append(f"  {c:5d}  {p!r}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"[OK] Stats written to {path}")
    print("\n--- STATS ---")
    print("\n".join(lines))


