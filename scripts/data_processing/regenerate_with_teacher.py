def informalize(text: str, rng: random.Random) -> str:
    rep = {
        "continuous function": "continuous",
        "differentiable function": "diff function",
        "differentiable": "diff",
        "converges uniformly": "converges",
        "uniformly continuous": "continuous",
        "absolute value": "mod",
        "if and only if": "iff",
        "for all": "every",
        "there exists": "has",
        "such that": "st",
        "implies": "->",
        "subset of": "in",
        "non-empty": "nonempty",
    }
    for k, v in rep.items():
        if rng.random() < 0.4:
            text = text.replace(k, v)
    return text


def drop_conditions(text: str, rng: random.Random) -> str:
    conds = ["closed ", "bounded ", "compact ", "finite ",
             "absolutely ", "uniformly ", "non-empty ",
             "connected ", "open ", "continuous "]
    for c in conds:
        if c in text and rng.random() < 0.5:
            text = text.replace(c, "", 1)
    return text


def garble(text: str, rng: random.Random) -> str:
    chars = list(text)
    n = max(1, int(len(chars) * rng.uniform(0.04, 0.12)))
    pool = "abcdefghijklmnopqrstuvwxyz0123456789$%^&*()_+-=[]{}|;':,./<>?"
    for _ in range(n):
        idx = rng.randint(0, len(chars) - 1)
        chars[idx] = rng.choice(pool)
    return "".join(chars)


def make_bad_note(stmt: str, rng: random.Random, mode: str = "auto") -> str:
    """mode: auto / informal / drop / garble / lower / preserve"""
    bad = stmt
    if mode == "preserve":
        return bad
    if mode == "auto":
        if rng.random() < 0.55:
            bad = informalize(bad, rng)
        if rng.random() < 0.45:
            bad = drop_conditions(bad, rng)
        if rng.random() < 0.35:
            bad = bad.lower().replace(".", "")
        if rng.random() < 0.25:
            bad = garble(bad, rng)
    elif mode == "garble":
        bad = garble(bad, rng)
    elif mode == "drop":
        bad = drop_conditions(bad, rng)
    elif mode == "informal":
        bad = informalize(bad, rng)
    elif mode == "lower":
        bad = bad.lower().replace(".", "")
    return bad


def wrap_with_conversation(stmt: str, rng: random.Random) -> tuple[str, str, str]:
    """Returns (prefix, body, suffix)"""
    prefix = rng.choice(WRAPPERS_PREFIX)
    suffix = rng.choice(WRAPPERS_SUFFIX)
    return prefix, stmt, suffix


