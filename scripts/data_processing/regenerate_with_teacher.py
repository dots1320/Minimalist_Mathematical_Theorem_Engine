# Source filtering
# --------------------------------------------------------------------------- #

def is_usable_wiki_theorem(stmt: str) -> bool:
    """Filter wikipedia entries: keep statement-like, not descriptive paragraphs."""
    if not stmt:
        return False
    L = len(stmt)
    if L < 30 or L > 500:
        return False
    # Heuristic: theorem statements contain math indicators or short verbs
    indicators = ["$", "if ", "iff", "every", "for all", "there exists",
                  "implies", "is a", "is the", "equals", "=", "\\", "theorem"]
    if not any(i in stmt.lower() for i in indicators):
        return False
    # Drop long descriptive paragraphs
    if stmt.count(". ") > 4:
        return False
    return True


