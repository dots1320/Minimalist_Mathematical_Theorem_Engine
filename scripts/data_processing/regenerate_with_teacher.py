THINK_RE = re.compile(r"<think>(.*?)</think>", re.DOTALL)


def extract_think_and_answer(text: str) -> tuple[str | None, str | None]:
    """Returns (think_content, answer_after_think). Either may be None on failure."""
    m = THINK_RE.search(text)
    if not m:
        return None, None
    think = m.group(1).strip()
    answer = text[m.end():].strip()
    return think, answer


def passes_quality(think: str | None, answer: str | None,
                   require_keywords: bool = True) -> tuple[bool, str]:
    if think is None:
        return False, "no_think_block"
    if answer is None or not answer.strip():
        return False, "no_answer"
    if len(think) < 30:
        return False, "think_too_short"
    if len(think) > 4000:
        return False, "think_too_long"
    if require_keywords:
        low = think.lower()
        if not any(kw in low for kw in THINK_QUALITY_KEYWORDS):
            return False, "no_quality_keyword"
    # Reject the old boilerplate template explicitly
    if "rigorous form is" in think and "imprecise shorthand" in think:
        return False, "boilerplate_template"
    if len(answer) > 800:
        return False, "answer_too_long"
    return True, "ok"


def build_record(bad_note_full: str, think: str, answer: str) -> dict:
    return {
        "instruction": SYSTEM_PROMPT,
        "input": bad_note_full,
        "output": f"<think>\n{think}\n</think>\n{answer}",
    }


