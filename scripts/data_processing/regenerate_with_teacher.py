def load_teacher(path: str):
    print(f"[INFO] Loading teacher tokenizer from {path}")
    tok = AutoTokenizer.from_pretrained(path, trust_remote_code=True)
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token

    print("[INFO] Configuring 4-bit (NF4) quantization for teacher")
    bnb = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_quant_type="nf4",
        bnb_4bit_compute_dtype=torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16,
        bnb_4bit_use_double_quant=True,
    )
    print(f"[INFO] Loading teacher model from {path} (~30s)")
    t0 = time.time()
    model = AutoModelForCausalLM.from_pretrained(
        path, quantization_config=bnb, device_map="auto",
        trust_remote_code=True,
    )
    model.eval()
    print(f"[INFO] Teacher loaded in {time.time() - t0:.1f}s")
    return model, tok


